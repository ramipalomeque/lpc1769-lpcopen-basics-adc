uint16_t GetCountADC(uint8_t chanel)
{
	uint16_t value = NO_ADC_VALUE;

	if(chanel == ADC_CH0 && buffer_adc_ch0 != NO_ADC_VALUE)
	{
		value = buffer_adc_ch0;
		buffer_adc_ch0 = NO_ADC_VALUE;
	}

	return value;
}

float GetTensionADC(uint8_t chanel)
{
	float value = NO_ADC_VALUE;

		if(chanel == ADC_CH0 && buffer_adc_ch0 != NO_ADC_VALUE)
		{
			value = (float)buffer_adc_ch0*ADC_LSB;
			buffer_adc_ch0 = NO_ADC_VALUE;
		}

		return value;
}
